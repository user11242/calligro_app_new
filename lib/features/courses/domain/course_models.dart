/// A course, read from the real course document (the fields
/// add_course_dashboard.dart writes). [raw] keeps the whole document for the
/// course pages that still take the Firestore map (course details).
class Course {
  final String id;
  final Map<String, dynamic> raw;

  final String courseName;
  final String courseDescription;
  final bool isAutoGeneratedName;
  final String teacherId;
  final String teacherName;
  final String teacherPhotoUrl;
  final String bannerUrl;
  final double price;

  /// The store product for this course, when the course stores one.
  final String? iapProductId;

  /// 'Beginner', 'Advanced', … (stored as selectedCategory).
  final String level;
  final String calligraphyStyle;
  final String writingType;
  final String ageCategory;
  final DateTime? startDate;
  final DateTime? endDate;
  final DateTime? startTime;
  final DateTime? endTime;
  final List<String> selectedDays;
  /// [{name, icon}] maps, as course creation stores them.
  final List<Map<String, dynamic>> requiredTools;
  final List<Map<String, dynamic>> curriculumSteps;
  final List<String> enrolledStudents;
  final int enrolledCount;

  /// 0 = no limit.
  final int maxStudents;
  final DateTime? createdAt;

  const Course({
    required this.id,
    this.raw = const {},
    this.courseName = '',
    this.courseDescription = '',
    this.isAutoGeneratedName = false,
    this.teacherId = '',
    this.teacherName = '',
    this.teacherPhotoUrl = '',
    this.bannerUrl = '',
    this.price = 0,
    this.iapProductId,
    this.level = '',
    this.calligraphyStyle = '',
    this.writingType = '',
    this.ageCategory = '',
    this.startDate,
    this.endDate,
    this.startTime,
    this.endTime,
    this.selectedDays = const [],
    this.requiredTools = const [],
    this.curriculumSteps = const [],
    this.enrolledStudents = const [],
    this.enrolledCount = 0,
    this.maxStudents = 0,
    this.createdAt,
  });

  bool get isFree => price <= 0;

  factory Course.fromMap(String id, Map<String, dynamic> d) {
    String s(String key) => d[key] is String ? d[key] as String : '';
    List<String> strings(Object? v) => v is List ? [for (final e in v) if (e != null) e.toString()] : const [];
    double number(Object? v) => v is num ? v.toDouble() : (double.tryParse('${v ?? ''}') ?? 0);
    DateTime? date(Object? v) {
      if (v is DateTime) return v;
      try {
        if (v != null && (v as dynamic).toDate is Function) return (v as dynamic).toDate() as DateTime;
      } catch (_) {}
      return v is String ? DateTime.tryParse(v) : null;
    }

    final enrolled = strings(d['enrolledStudents']);
    final product = s('iapProductId');
    return Course(
      id: id,
      raw: Map.unmodifiable(d),
      courseName: s('courseName'),
      courseDescription: s('courseDescription'),
      isAutoGeneratedName: d['isAutoGeneratedName'] == true,
      teacherId: s('teacherId'),
      teacherName: s('teacherName'),
      teacherPhotoUrl: s('teacherProfilePic'),
      bannerUrl: s('courseBanner'),
      price: number(d['price']),
      iapProductId: product.isEmpty ? null : product,
      level: s('selectedCategory'),
      calligraphyStyle: s('calligraphyStyle'),
      writingType: s('writingType'),
      ageCategory: s('ageCategory'),
      startDate: date(d['startDate']),
      endDate: date(d['endDate']),
      startTime: date(d['startTime']) ?? date(d['selectedTime']),
      endTime: date(d['endTime']),
      selectedDays: strings(d['selectedDays']),
      requiredTools: [
        for (final t in (d['requiredTools'] is List ? d['requiredTools'] as List : const []))
          if (t is Map) Map<String, dynamic>.from(t),
      ],
      curriculumSteps: [
        for (final step in (d['curriculumSteps'] is List ? d['curriculumSteps'] as List : const []))
          if (step is Map) Map<String, dynamic>.from(step),
      ],
      enrolledStudents: enrolled,
      enrolledCount: d['enrolledCount'] is num ? (d['enrolledCount'] as num).toInt() : enrolled.length,
      maxStudents: number(d['maxStudents']).toInt(),
      createdAt: date(d['createdAt']),
    );
  }
}

/// The teacher block on a course page, read once.
class CourseTeacherSummary {
  final String id;
  final String name;
  final String photoUrl;
  final double averageRating;
  final int reviewCount;
  final int followerCount;
  final int courseCount;
  final int totalStudents;
  final List<String> spokenLanguages;

  /// Flag emoji for the teacher's country ('' when unknown).
  final String countryFlag;

  const CourseTeacherSummary({
    required this.id,
    this.name = '',
    this.photoUrl = '',
    this.averageRating = 0,
    this.reviewCount = 0,
    this.followerCount = 0,
    this.courseCount = 0,
    this.totalStudents = 0,
    this.spokenLanguages = const [],
    this.countryFlag = '',
  });
}

/// Catalogue chips. Matching uses the STORED values, never translated labels.
enum CourseFilter {
  all,
  myCourses,
  thuluth('Thuluth'),
  naskh('Naskh'),
  diwani('Diwani'),
  kufi('Kufi'),
  ruqah("Ruq'ah"),
  beginner('Beginner'),
  advanced('Advanced');

  const CourseFilter([this.storedValue]);

  /// The calligraphyStyle / selectedCategory value this chip matches.
  final String? storedValue;

  bool get isLevel => this == beginner || this == advanced;
}

