/**
 * firestore.rules for courses: who sees paid materials, who may create a
 * course, and who may write money records. Emulator:
 *   firebase emulators:exec --only firestore --project demo-calligro \
 *     "cd functions && npx jest test/course_rules.test.js"
 */
const fs = require('fs');
const path = require('path');
const { assertFails, assertSucceeds, initializeTestEnvironment } = require('@firebase/rules-unit-testing');
const { doc, setDoc, getDoc, updateDoc, deleteDoc, addDoc, collection, arrayUnion, serverTimestamp, writeBatch, Timestamp, deleteField } = require('firebase/firestore');

let env;
const as = (uid) => env.authenticatedContext(uid).firestore();
const guest = () => env.unauthenticatedContext().firestore();

beforeAll(async () => {
  env = await initializeTestEnvironment({
    projectId: 'demo-calligro-courses',
    firestore: { host: '127.0.0.1', port: 8080, rules: fs.readFileSync(path.join(__dirname, '../../firestore.rules'), 'utf8') },
  });
});
afterAll(() => env.cleanup());

beforeEach(async () => {
  await env.clearFirestore();
  await env.withSecurityRulesDisabled(async (ctx) => {
    const db = ctx.firestore();
    await setDoc(doc(db, 'users/admin'), { role: 'admin' });
    await setDoc(doc(db, 'users/teach'), { role: 'teacher', status: 'approved', name: 'Ustadh Ali', photoUrl: 'ali.jpg' });
    await setDoc(doc(db, 'users/teach2'), { role: 'teacher', status: 'approved', name: 'Other Teacher' });
    await setDoc(doc(db, 'users/legacyTeach'), { role: 'teacher', approved: true });
    await setDoc(doc(db, 'users/pending'), { role: 'teacher', status: 'pending' });
    await setDoc(doc(db, 'users/student'), { role: 'student' });
    await setDoc(doc(db, 'users/outsider'), { role: 'student' });
    await setDoc(doc(db, 'courses/c1'), { teacherId: 'teach', price: 100, enrolledStudents: ['student'], enrolledCount: 1 });
    await setDoc(doc(db, 'courses/empty'), { teacherId: 'teach', price: 100, enrolledStudents: [], enrolledCount: 0 });
    await setDoc(doc(db, 'courses/c1/materials/m1'), { title: 'Week 1', files: [{ fileUrl: 'https://storage/secret.pdf' }] });
  });
});

const names = { teach: 'Ustadh Ali', teach2: 'Other Teacher' };
const newCourse = (teacherId) => ({ teacherId, teacherName: names[teacherId] || '', courseName: 'New', price: 50, enrolledStudents: [], enrolledCount: 0 });

// Exactly what the app writes (CourseDraft.toDocument + FirestoreCourseAuthoring.create).
const appCourse = (over = {}) => ({
  courseName: 'Diwani Basics', courseDescription: '', writingType: 'Arabic Calligraphy', calligraphyStyle: 'Diwani',
  courseBanner: 'assets/courses_backgrounds/diwani.jpg', teacherProfilePic: 'ali.jpg', levelColor: 'Beginner',
  selectedCategory: 'Beginner', ageCategory: 'Adults', startDate: Timestamp.fromDate(new Date('2026-12-01')),
  endDate: Timestamp.fromDate(new Date('2027-01-01')), selectedDays: ['Monday'], teacherId: 'teach',
  teacherName: 'Ustadh Ali', enrolledStudents: [], enrolledCount: 0, price: 80, iapProductId: 'com.yazan.calligro.tier_80',
  calligroMeetLink: 'room', maxStudents: 10, requiredTools: [], isAutoGeneratedName: false, curriculumSteps: ['Alif'],
  createdAt: serverTimestamp(), ...over,
});
const strip = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined));

describe('paid course materials', () => {
  it('enrolled students, the teacher and admins can read them', async () => {
    await assertSucceeds(getDoc(doc(as('student'), 'courses/c1/materials/m1')));
    await assertSucceeds(getDoc(doc(as('teach'), 'courses/c1/materials/m1')));
    await assertSucceeds(getDoc(doc(as('admin'), 'courses/c1/materials/m1')));
  });
  it('people who did not buy the course cannot (THE LEAK)', async () => {
    await assertFails(getDoc(doc(as('outsider'), 'courses/c1/materials/m1')));
    await assertFails(getDoc(doc(guest(), 'courses/c1/materials/m1')));
  });
  it('only the teacher (or an admin) manages them', async () => {
    await assertSucceeds(setDoc(doc(as('teach'), 'courses/c1/materials/m2'), { title: 'Week 2' }));
    await assertFails(setDoc(doc(as('student'), 'courses/c1/materials/m3'), { title: 'spam' }));
  });
});

describe('creating courses', () => {
  it('approved teachers can (including older "approved: true" accounts)', async () => {
    await assertSucceeds(setDoc(doc(as('teach'), 'courses/n1'), newCourse('teach')));
    await assertSucceeds(setDoc(doc(as('legacyTeach'), 'courses/n2'), newCourse('legacyTeach')));
  });
  it('students and not-yet-approved teachers cannot', async () => {
    await assertFails(setDoc(doc(as('student'), 'courses/n3'), newCourse('student')));
    await assertFails(setDoc(doc(as('pending'), 'courses/n4'), newCourse('pending')));
  });
  it('nobody creates a course for someone else, or pre-filled with students', async () => {
    await assertFails(setDoc(doc(as('teach'), 'courses/n5'), newCourse('legacyTeach')));
    await assertFails(setDoc(doc(as('teach'), 'courses/n6'), { ...newCourse('teach'), enrolledStudents: ['student'], enrolledCount: 1 }));
  });
});

describe('enrolment and money records are server-only', () => {
  it('a student cannot add themselves to a course', () =>
    assertFails(updateDoc(doc(as('outsider'), 'courses/c1'), { enrolledStudents: arrayUnion('outsider') })));
  it('a signed-in user cannot write a fake transaction (THE "admin_bypass" HOLE)', () =>
    assertFails(addDoc(collection(as('outsider'), 'transactions'), {
      studentId: 'outsider', teacherId: 'teach', amount: 99999, status: 'completed', source: 'admin_bypass', createdAt: serverTimestamp(),
    })));
  it('admins still can (development "join for free" button)', () =>
    assertSucceeds(addDoc(collection(as('admin'), 'transactions'), { studentId: 'admin', amount: 0, source: 'admin_bypass', status: 'completed' })));
  it('nobody writes orders from a client', () =>
    assertFails(setDoc(doc(as('student'), 'orders/x'), { uid: 'student', courseId: 'c1' })));
});

describe('the course document the app writes', () => {
  it('is accepted together with its private meeting settings, in one batch', async () => {
    const db = as('teach');
    const b = writeBatch(db);
    b.set(doc(db, 'courses/fresh'), appCourse());
    b.set(doc(db, 'courses/fresh/private/meetingConfig'), { calligroMeetLink: 'room', classroomPassword: 'pw', createdAt: serverTimestamp() });
    await assertSucceeds(b.commit());
  });
  it('free courses (no product) are accepted', () =>
    assertSucceeds(setDoc(doc(as('teach'), 'courses/free'), strip(appCourse({ price: 0, iapProductId: undefined })))));
  it('a product that does not match the price is refused (buy cheap tier, get expensive course)', () =>
    assertFails(setDoc(doc(as('teach'), 'courses/x'), appCourse({ price: 200, iapProductId: 'com.yazan.calligro.tier_60' }))));
  it('a negative price or a non-number is refused', async () => {
    await assertFails(setDoc(doc(as('teach'), 'courses/x1'), strip(appCourse({ price: -10, iapProductId: undefined }))));
    await assertFails(setDoc(doc(as('teach'), 'courses/x2'), appCourse({ price: '80' })));
  });
  it('a phone-clock / future createdAt is refused (pinning a course to the top)', () =>
    assertFails(setDoc(doc(as('teach'), 'courses/x'), appCourse({ createdAt: Timestamp.fromDate(new Date('2030-01-01')) }))));
  it('another teacher\'s name is refused (impersonation)', () =>
    assertFails(setDoc(doc(as('teach'), 'courses/x'), appCourse({ teacherName: 'Other Teacher' }))));
  it('zero or fractional seats are refused', async () => {
    await assertFails(setDoc(doc(as('teach'), 'courses/x1'), appCourse({ maxStudents: 0 })));
    await assertFails(setDoc(doc(as('teach'), 'courses/x2'), appCourse({ maxStudents: 2.5 })));
  });
  it('meeting settings cannot be written for someone else\'s course', () =>
    assertFails(setDoc(doc(as('teach2'), 'courses/c1/private/meetingConfig'), { classroomPassword: 'hijack' })));
});

// TEMPORARY OLD-APP BRIDGE (remove after the forced update, see docs/KNOWN_ISSUES.md):
// the store app (1.0.24) stamps new courses with the phone's clock, not the server's.
describe('store app 1.0.24 can still create courses (temporary bridge)', () => {
  const now = (offsetMs = 0) => Timestamp.fromDate(new Date(Date.now() + offsetMs));
  it('the phone-clock createdAt of right now is accepted', () =>
    assertSucceeds(setDoc(doc(as('teach'), 'courses/old1'), appCourse({ createdAt: now(), price: 50.0, iapProductId: 'com.yazan.calligro.tier_50' }))));
  it('a phone clock a few minutes off either way is accepted', async () => {
    await assertSucceeds(setDoc(doc(as('teach'), 'courses/old2'), appCourse({ createdAt: now(-4 * 60 * 1000) })));
    await assertSucceeds(setDoc(doc(as('teach'), 'courses/old3'), appCourse({ createdAt: now(4 * 60 * 1000) })));
  });
  it('a backdated or future-dated course is still refused', async () => {
    await assertFails(setDoc(doc(as('teach'), 'courses/old4'), appCourse({ createdAt: now(-60 * 60 * 1000) })));
    await assertFails(setDoc(doc(as('teach'), 'courses/old5'), appCourse({ createdAt: now(60 * 60 * 1000) })));
    await assertFails(setDoc(doc(as('teach'), 'courses/old6'), appCourse({ createdAt: 'yesterday' })));
  });
  it('everything else stays locked (students pre-filled, wrong teacher)', async () => {
    await assertFails(setDoc(doc(as('teach'), 'courses/old7'), appCourse({ createdAt: now(), enrolledStudents: ['student'], enrolledCount: 1 })));
    await assertFails(setDoc(doc(as('teach2'), 'courses/old8'), appCourse({ createdAt: now() })));
  });
});

describe('changing an existing course', () => {
  it('the owner can reschedule a session and cancel it', async () => {
    await assertSucceeds(updateDoc(doc(as('teach'), 'courses/c1'), { rescheduledSession: { newStartTime: Timestamp.now() } }));
    await assertSucceeds(updateDoc(doc(as('teach'), 'courses/c1'), { rescheduledSession: deleteField() }));
  });
  it('the owner cannot touch students, seats, price, product or owner', async () => {
    const c = doc(as('teach'), 'courses/c1');
    await assertFails(updateDoc(c, { enrolledStudents: arrayUnion('friend') }));
    await assertFails(updateDoc(c, { enrolledStudents: [] }));
    await assertFails(updateDoc(c, { enrolledCount: 0 }));
    await assertFails(updateDoc(c, { price: 0 }));
    await assertFails(updateDoc(c, { iapProductId: 'com.yazan.calligro.tier_60' }));
    await assertFails(updateDoc(c, { teacherId: 'teach2' }));
    await assertFails(updateDoc(c, { maxStudents: 1000 }));
  });
  it('the owner\'s name on the course follows their profile only (account deletion)', async () => {
    await assertFails(updateDoc(doc(as('teach'), 'courses/c1'), { teacherName: 'Fake Famous Teacher' }));
    const db = as('teach');
    const b = writeBatch(db);
    b.update(doc(db, 'users/teach'), { name: 'حساب محذوف', photoUrl: null });
    b.update(doc(db, 'courses/c1'), { teacherName: 'حساب محذوف', teacherProfilePic: null });
    await assertSucceeds(b.commit());
  });
  it('other teachers cannot change it at all; admins can', async () => {
    await assertFails(updateDoc(doc(as('teach2'), 'courses/c1'), { rescheduledSession: {} }));
    await assertSucceeds(updateDoc(doc(as('admin'), 'courses/c1'), { maxStudents: 50 }));
  });
  it('a course with paid students cannot be deleted by its teacher; an empty one can', async () => {
    await assertFails(deleteDoc(doc(as('teach'), 'courses/c1')));
    await assertSucceeds(deleteDoc(doc(as('teach'), 'courses/empty')));
    await assertSucceeds(deleteDoc(doc(as('admin'), 'courses/c1')));
  });
});

describe('moved classes are written by the server only', () => {
  it('the teacher cannot write the move list, the original range, the time zone or the dates', async () => {
    const db = as('teach');
    for (const field of [
      { sessionMoves: [{ originalStart: Timestamp.now(), newStart: Timestamp.now(), newEnd: Timestamp.now() }] },
      { scheduleStartDate: Timestamp.now() },
      { scheduleEndDate: Timestamp.now() },
      { scheduleUtcOffsetMinutes: 180 },
      { startDate: Timestamp.now() },
      { endDate: Timestamp.fromDate(new Date('2020-01-01')) }, // would unlock payouts early
    ]) {
      await assertFails(updateDoc(doc(db, 'courses/c1'), field));
    }
  });
});

describe('notifications are written by the server', () => {
  const notif = (courseId) => ({ title: 'Session moved', message: 'x', type: 'reschedule', courseId, isRead: false, createdAt: serverTimestamp() });
  it('teachers no longer write into students\' inboxes (that was the second copy of every reschedule notice)', async () => {
    await assertFails(addDoc(collection(as('teach'), 'users/student/notifications'), notif('c1')));
    await assertFails(addDoc(collection(as('teach'), 'users/outsider/notifications'), { title: 'Your account is locked, click here' }));
  });
  it('nobody fills someone else\'s inbox through the old "userId == me" back door', () =>
    assertFails(addDoc(collection(as('outsider'), 'users/student/notifications'), { userId: 'outsider', title: 'Free course, click here' })));
  it('admins still can (payout status)', () =>
    assertSucceeds(addDoc(collection(as('admin'), 'users/teach/notifications'), { title: 'Payout Completed', body: 'x', type: 'payout_status', read: false })));
});
