Course courseDoc(
  String id, {
  String name = 'Thuluth Foundations',
  String teacherId = 't1',
  String teacher = 'Ustadh Ali',
  double price = 100,
  Object? iapProductId = 'com.yazan.calligro.tier_100',
  String style = 'Thuluth',
  String level = 'Beginner',
  List<String> enrolled = const [],
  int? enrolledCount,
  int maxStudents = 3,
}) =>
    Course.fromMap(
      id,
      realCourseData(
        name: name,
        teacherId: teacherId,
        teacher: teacher,
        price: price,
        iapProductId: price <= 0 ? null : iapProductId,
        style: style,
        level: level,
        enrolled: enrolled,
        enrolledCount: enrolledCount,
        maxStudents: maxStudents,
      ),
    );
